class FingerprintDataset(Dataset):
    def __init__(self, files, labels, tfm):
        self.files, self.labels, self.tfm = files, labels, tfm
    def __len__(self): return len(self.files)
    def __getitem__(self, i):
        img = np.array(Image.open(self.files[i]).convert("RGB"))
        img = self.tfm(image=img)["image"]
        return img, torch.tensor(self.labels[i])

cnt = Counter(y_train)
weights = [1.0 / cnt[l] for l in y_train]
sampler = WeightedRandomSampler(weights, len(weights), replacement=True)

train_dl = DataLoader(
    FingerprintDataset(X_train, y_train, train_tfms),
    batch_size=16, sampler=sampler, num_workers=2, pin_memory=True
)
val_dl = DataLoader(
    FingerprintDataset(X_val, y_val, val_tfms),
    batch_size=32, num_workers=2, pin_memory=True
)
test_dl = DataLoader(
    FingerprintDataset(X_test, y_test, val_tfms),
    batch_size=32, num_workers=2, pin_memory=True
)

