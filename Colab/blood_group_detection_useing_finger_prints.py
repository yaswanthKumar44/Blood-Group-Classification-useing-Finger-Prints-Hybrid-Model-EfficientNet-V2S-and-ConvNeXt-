# 6️⃣ STRONG HYBRID MODEL
# =========================================================
class StrongHybrid(nn.Module):
    def __init__(self, n):
        super().__init__()
        self.eff = timm.create_model("tf_efficientnetv2_s.in21k", pretrained=True, num_classes=0)
        self.cnx = timm.create_model("convnext_small", pretrained=True, num_classes=0)
        self.bn1 = nn.BatchNorm1d(self.eff.num_features)
        self.bn2 = nn.BatchNorm1d(self.cnx.num_features)
        self.head = nn.Sequential(
            nn.Linear(self.eff.num_features + self.cnx.num_features, 1024),
            nn.BatchNorm1d(1024),
            nn.GELU(),
            nn.Dropout(0.35),
            nn.Linear(1024, n)
        )

    def forward(self, x):
        f1 = self.bn1(self.eff(x))
        f2 = self.bn2(self.cnx(x))
        return self.head(torch.cat([f1, f2], dim=1))

model = StrongHybrid(len(classes)).to(device)
print("✅ Model initialized")

# =========================================================
# 7️⃣ LOSS, OPTIMIZER, SCHEDULER
# =========================================================
class_weights = torch.tensor([1.0 / cnt[i] for i in range(len(classes))], device=device)

criterion = nn.CrossEntropyLoss(weight=class_weights, label_smoothing=0.05)

optimizer = torch.optim.AdamW(model.parameters(), lr=3e-4, weight_decay=1e-4)

scheduler = torch.optim.lr_scheduler.CosineAnnealingWarmRestarts(
    optimizer, T_0=10, T_mult=2, eta_min=1e-6
)

scaler = torch.cuda.amp.GradScaler()

# =========================================================
# 8️⃣ TRAINING (STORE ACC & LOSS)
# =========================================================
EPOCHS = 70
patience, wait = 10, 0
best_val_acc = 0.0

train_acc_hist, val_acc_hist = [], []
train_loss_hist, val_loss_hist = [], []

for epoch in range(EPOCHS):
    model.train()
    tr_p, tr_y = [], []
    train_loss = 0.0

    for x, y in tqdm(train_dl, desc=f"Epoch {epoch+1}/{EPOCHS}"):
        x, y = x.to(device), y.to(device)
        optimizer.zero_grad()

        with torch.cuda.amp.autocast():
            out = model(x)
            loss = criterion(out, y)

        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()

        train_loss += loss.item()
        tr_p += out.argmax(1).cpu().tolist()
        tr_y += y.cpu().tolist()

    scheduler.step()
    train_loss /= len(train_dl)
    train_acc = accuracy_score(tr_y, tr_p)

    model.eval()
    v_p, v_y = [], []
    val_loss = 0.0

    with torch.no_grad():
        for x, y in val_dl:
            x, y = x.to(device), y.to(device)
            out = model(x)
            loss = criterion(out, y)
            val_loss += loss.item()
            v_p += out.argmax(1).cpu().tolist()
            v_y += y.cpu().tolist()

    val_loss /= len(val_dl)
    val_acc = accuracy_score(v_y, v_p)

    train_acc_hist.append(train_acc)
    val_acc_hist.append(val_acc)
    train_loss_hist.append(train_loss)
    val_loss_hist.append(val_loss)

    print(f"📊 Epoch {epoch+1}: TrainAcc={train_acc:.4f}, ValAcc={val_acc:.4f}")

    if val_acc > best_val_acc:
        best_val_acc = val_acc
        wait = 0
        torch.save(model.state_dict(), "best_model.pth")
        print("✅ Best model saved")
    else:
        wait += 1
        if wait >= patience:
            print("🛑 Early stopping")
            break

